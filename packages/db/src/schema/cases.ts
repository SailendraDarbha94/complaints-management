/**
 * A respondent's own state, independent of the case. One complaint may name several
 * dentists and an establishment; each gets its own notice ladder and its own outcome.
 */
export const caseRespondent = pgTable(
  'case_respondent',
  {
    id: uuid('id').primaryKey().defaultRandom(),
    councilId: uuid('council_id')
      .notNull()
      .references(() => council.id, { onDelete: 'restrict' }),
    caseFileId: uuid('case_file_id')
      .notNull()
      .references(() => caseFile.id, { onDelete: 'restrict' }),
    casePartyId: uuid('case_party_id')
      .notNull()
      .references(() => casePartyTable.id, { onDelete: 'restrict' }),

    noticeState: noticeStateEnum('notice_state').notNull().default('not_issued'),
    /**
     * Increments ONLY when the officer confirms a despatch. No timer touches this.
     * A timer-driven count would become the legal basis for an ex parte finding against
     * a named dentist, on a system whose premise is that things get forgotten.
     */
    noticeCount: integer('notice_count').notNull().default(0),
    replyDueAt: date('reply_due_at'),
    firstReplyAt: timestamp('first_reply_at', { withTimezone: true }),

    /** Computed from despatched notices with proof of service — never from a reminder. */
    exParteEligible: boolean('ex_parte_eligible').notNull().default(false),
    exParteAt: timestamp('ex_parte_at', { withTimezone: true }),
    exParteReason: text('ex_parte_reason'),

    droppedAt: timestamp('dropped_at', { withTimezone: true }),
    droppedReason: text('dropped_reason'),

    createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [
    uniqueIndex('case_respondent_uq').on(t.caseFileId, t.casePartyId),
    index('case_respondent_case_ix').on(t.councilId, t.caseFileId, t.noticeState),
    check(
      'case_respondent_ex_parte_needs_reason',
      sql`(ex_parte_at IS NULL) OR (ex_parte_reason IS NOT NULL)`,
    ),
    check('case_respondent_drop_needs_reason', sql`(dropped_at IS NULL) OR (dropped_reason IS NOT NULL)`),
  ],
);

