/**
 * Every touch — email, phone call, WhatsApp, post. The satisfaction primitive for
 * follow-ups: an inbound contact from the waiting party closes the timer.
 *
 * Phone calls matter here. "Telephoned twice, no answer" is half of an ex parte
 * justification, and it is invisible unless it is written down.
 */
export const contactEvent = pgTable(
  'contact_event',
  {
    id: uuid('id').primaryKey().defaultRandom(),
    councilId: uuid('council_id')
      .notNull()
      .references(() => council.id, { onDelete: 'restrict' }),
    caseFileId: uuid('case_file_id')
      .notNull()
      .references(() => caseFile.id, { onDelete: 'restrict' }),
    partyId: uuid('party_id').references(() => party.id, { onDelete: 'set null' }),
    channel: contactChannelEnum('channel').notNull(),
    direction: contactDirectionEnum('direction').notNull(),
    purpose: text('purpose'),
    summary: text('summary').notNull(),
    outcome: text('outcome'), // 'no_answer' | 'spoke' | 'left_message' | …
    occurredAt: timestamp('occurred_at', { withTimezone: true }).notNull(),
    recordedAt: timestamp('recorded_at', { withTimezone: true }).notNull().defaultNow(),
    recordedBy: uuid('recorded_by').references(() => appUser.id, { onDelete: 'set null' }),
  },
  (t) => [index('contact_event_case_ix').on(t.councilId, t.caseFileId, t.occurredAt)],
);

