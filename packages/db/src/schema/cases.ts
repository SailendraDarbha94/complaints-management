/**
 * Dates are events, not columns. Append-only, so adding a register column later is a view
 * change rather than a migration.
 */
export const caseMilestone = pgTable(
  'case_milestone',
  {
    id: uuid('id').primaryKey().defaultRandom(),
    councilId: uuid('council_id')
      .notNull()
      .references(() => council.id, { onDelete: 'restrict' }),
    caseFileId: uuid('case_file_id')
      .notNull()
      .references(() => caseFile.id, { onDelete: 'restrict' }),
    milestone: milestoneEnum('milestone').notNull(),
    occurredAt: timestamp('occurred_at', { withTimezone: true }).notNull(),
    /**
     * Mandatory. Anything other than `recorded` is footnoted in every export and printed
     * case file — which is what stops a reconstructed backlog date from becoming
     * indistinguishable from a recorded fact in an RTI reply or a writ petition.
     */
    dateSource: dateSourceEnum('date_source').notNull(),
    caseRespondentId: uuid('case_respondent_id').references(() => caseRespondent.id, {
      onDelete: 'set null',
    }),
    seqNo: integer('seq_no'),
    refTable: text('ref_table'),
    refId: uuid('ref_id'),
    note: text('note'),
    recordedAt: timestamp('recorded_at', { withTimezone: true }).notNull().defaultNow(),
    recordedBy: uuid('recorded_by').references(() => appUser.id, { onDelete: 'set null' }),
  },
  (t) => [index('case_milestone_case_ix').on(t.councilId, t.caseFileId, t.occurredAt)],
);

